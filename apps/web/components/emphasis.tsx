/**
 * 技能文案里的 `**这样**` → `<strong>`。
 *
 * `lib/skills.ts` 的 l0/l1 是从知识库（04-skills-catalog）带下来的，强调标记一路留着——
 * 标的全是**最容易读漏的那半句**（吟游的「全场」、神授的「一定要」、专精的「你的色」）。
 * 在此之前没有任何一处渲染它，于是玩家看到的是字面的 `**全场**都吃它的效果`：
 * 既漏掉了重点，又像是文案坏了。
 *
 * **不引 markdown 解析器**：这些字符串里只用到强调这一种标记，`split("**")` 就够了
 * （奇数段就在一对 `**` 之间）。落单的 `**` 退化成不加粗，不会炸。
 * 哪天文案真需要列表/链接再谈解析器——现在引一个就是给不存在的场景付钱。
 *
 * 这个文件**不带 "use client"**：百科页是刻意的零客户端 JS 的服务端组件，
 * 从一个 client 模块里 import 会把整页拖成 client。
 */
export function Emphasis({ text }: { text: string }) {
  return (
    <>
      {text.split("**").map((part, i) => (i % 2 === 1 ? <strong key={i}>{part}</strong> : part))}
    </>
  );
}
